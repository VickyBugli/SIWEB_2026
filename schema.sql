-- =====================================================================
-- SIWeb - Script de creación de la base de datos (PostgreSQL)
-- Crea las tablas del modelo entidad-relación.
-- Se puede ejecutar varias veces: primero borra las tablas si existen.
-- =====================================================================

DROP TABLE IF EXISTS accion, valoracion, reporte, comentario,
                     observacion, material, materia, usuario, rol CASCADE;

-- ---------------------------------------------------------------------
-- ROL: estudiante, moderador, administrador
-- ---------------------------------------------------------------------
CREATE TABLE rol (
    id_rol       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol   VARCHAR(30)  NOT NULL UNIQUE,
    descripcion  VARCHAR(200)
);

-- ---------------------------------------------------------------------
-- USUARIO: solo se guardan cuentas ya verificadas
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_apellido  VARCHAR(100) NOT NULL,
    email            VARCHAR(150) NOT NULL UNIQUE,
    contrasena_hash  VARCHAR(255) NOT NULL,
    es_avanzado      BOOLEAN      NOT NULL DEFAULT FALSE,
    id_rol           INTEGER      NOT NULL REFERENCES rol (id_rol)
);

-- ---------------------------------------------------------------------
-- MATERIA
-- ---------------------------------------------------------------------
CREATE TABLE materia (
    id_materia      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_materia  VARCHAR(100) NOT NULL UNIQUE,
    anio_carrera    INTEGER      NOT NULL CHECK (anio_carrera BETWEEN 1 AND 6)
);

-- ---------------------------------------------------------------------
-- MATERIAL: el archivo se guarda en la carpeta uploads/,
-- la base solo guarda su ruta. Borrado lógico mediante "estado".
-- ---------------------------------------------------------------------
CREATE TABLE material (
    id_material        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_archivo     VARCHAR(255) NOT NULL,
    formato_archivo    VARCHAR(100) NOT NULL,
    fecha_publicacion  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    ruta_archivo       VARCHAR(255) NOT NULL,
    tipo_material      VARCHAR(20)  NOT NULL
                       CHECK (tipo_material IN ('apunte', 'resumen', 'tp')),
    descripcion        VARCHAR(500) NOT NULL,
    tamano             INTEGER      NOT NULL CHECK (tamano >= 0),
    estado             VARCHAR(20)  NOT NULL DEFAULT 'publicado'
                       CHECK (estado IN ('publicado', 'eliminado')),
    id_materia         INTEGER      NOT NULL REFERENCES materia (id_materia),
    id_usuario         INTEGER      NOT NULL REFERENCES usuario (id_usuario)
);

-- ---------------------------------------------------------------------
-- OBSERVACION (supertipo de la generalización)
-- Subtipos: COMENTARIO, VALORACION, REPORTE (total y disjunta).
-- Cada subtipo usa como clave primaria el id de su observación.
-- ---------------------------------------------------------------------
CREATE TABLE observacion (
    id_observacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_usuario      INTEGER     NOT NULL REFERENCES usuario (id_usuario),
    id_material     INTEGER     NOT NULL REFERENCES material (id_material)
);

CREATE TABLE comentario (
    id_observacion  INTEGER PRIMARY KEY REFERENCES observacion (id_observacion),
    contenido       VARCHAR(500) NOT NULL,
    descripcion     VARCHAR(500)
);

-- La regla "un voto por usuario por material" se controla en el endpoint,
-- porque usuario y material están en la tabla observacion.
CREATE TABLE valoracion (
    id_observacion  INTEGER PRIMARY KEY REFERENCES observacion (id_observacion),
    puntuacion      INTEGER NOT NULL CHECK (puntuacion BETWEEN 1 AND 5)
);

-- Si id_comentario es NULL se reporta el material;
-- si tiene valor, se reporta ese comentario (relación "denuncia").
CREATE TABLE reporte (
    id_observacion    INTEGER PRIMARY KEY REFERENCES observacion (id_observacion),
    motivo_reporte    VARCHAR(300) NOT NULL,
    estado            VARCHAR(30)  NOT NULL DEFAULT 'pendiente'
                      CHECK (estado IN ('pendiente', 'desestimado', 'solicitud_eliminacion',
                                        'eliminado', 'rechazado')),
    fecha_resolucion  TIMESTAMPTZ,
    id_comentario     INTEGER REFERENCES comentario (id_observacion)
);

-- ---------------------------------------------------------------------
-- ACCION: historial de moderación (quién hizo qué y cuándo)
-- ---------------------------------------------------------------------
CREATE TABLE accion (
    id_accion     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_accion   VARCHAR(30)  NOT NULL
                  CHECK (tipo_accion IN ('desestimar_reporte', 'solicitar_eliminacion',
                                         'aprobar_eliminacion', 'rechazar_eliminacion')),
    descripcion   VARCHAR(300),
    fecha_accion  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    id_usuario    INTEGER      NOT NULL REFERENCES usuario (id_usuario),
    id_reporte    INTEGER      NOT NULL REFERENCES reporte (id_observacion)
);
